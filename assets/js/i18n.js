const Lang = (function () {
  "use strict";
  const KEY = "carminello_lang";
  let cur = "it";
  try { cur = localStorage.getItem(KEY) || ((navigator.language || "it").toLowerCase().startsWith("en") ? "en" : "it"); } catch (e) {}
  function get() { return cur; }
  function t(key) { return (I18N[cur] && I18N[cur][key]) || I18N.it[key] || key; }
  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
    root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.getAttribute("data-i18n-html")); });
    root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.getAttribute("data-i18n-ph")); });
    document.documentElement.lang = cur;
    document.querySelectorAll("[data-lang-btn]").forEach(b => b.classList.toggle("on", b.getAttribute("data-lang-btn") === cur));
  }
  function set(l) {
    cur = l === "en" ? "en" : "it";
    try { localStorage.setItem(KEY, cur); } catch (e) {}
    apply();
    document.dispatchEvent(new CustomEvent("lang:change", { detail: cur }));
  }
  // nome prodotto nella lingua giusta
  function pick(obj, base) { return (cur === "en" && obj[base + "_en"]) || obj[base + "_it"] || obj[base] || ""; }
  return { get, t, apply, set, pick };
})();
